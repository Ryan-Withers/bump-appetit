/** Every name icon() answers to. Handy for a sprite audit or a golden test. */
export const ICON_NAMES = Object.freeze(Object.keys(BODIES));

// The result is written with innerHTML, so keep quotes and angle brackets out
// of a caller-supplied class name.
function safeCls(value) {
  return String(value || '').replace(/[^a-zA-Z0-9 _-]/g, '').trim();
}

export function icon(name, { size = 24, cls = '' } = {}) {
  const body = BODIES[name];
  if (!body) return '';

  const px = Number(size) > 0 ? Number(size) : 24;
  const extra = safeCls(cls);
  const classAttr = extra ? `icon ${extra}` : 'icon';

  return `<svg class="${classAttr}" width="${px}" height="${px}" viewBox="0 0 24 24" `
    + 'fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" '
    + 'stroke-linejoin="round" aria-hidden="true" focusable="false">'
    + `${body}</svg>`;
}
